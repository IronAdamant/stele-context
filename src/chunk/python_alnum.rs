//! Code points Rust's `is_alphanumeric` accepts that Python word class does not.
//!
//! Python's word class is general categories L and N, plus underscore.
//! Rust's alphabetic property also includes Other_Alphabetic marks
//! (Devanagari vowel signs, for example). Those marks are `[^\w\s]` tokens.

/// Python word class: categories L and N, plus underscore.
#[inline]
pub(crate) fn is_python_word(ch: char) -> bool {
    if ch.is_ascii() {
        return ch.is_ascii_alphanumeric() || ch == '_';
    }
    ch.is_alphanumeric() && !other_alphabetic(ch)
}

